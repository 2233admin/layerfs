// `/.lww` for the replay (owner, 2026-10-18, watch-out S4): the product's
// last-writer-wins rule file, generated from every dsh `.gitignore` in the
// tree. Paths both sides of a merge changed under ignored, regenerated state
// (node_modules, build output) then take the newer side instead of
// conflicting; the merged result re-runs `pnpm install`, checked by the
// on-top install oracle.
//
// Generation: the root `.gitignore`'s patterns as written, then each nested
// `.gitignore`'s patterns rewritten with its folder prefix, shallower folders
// first so deeper rules win (the last matching rule decides):
//   unanchored `p`      -> `dir/**/p`
//   anchored `/p`, `a/p` -> `dir/p`, `dir/a/p`
//   `!` kept in front; a trailing `/` kept (lww.rs ignores it, as for anchoring).
// `lwwMatch` ports lww.rs `Rules::matching` (a rule matching a parent folder
// matches the path), so the replay can check the rules against git's own
// check-ignore before relying on them.

import * as childProcess from "node:child_process";
import * as closure from "./closure.mjs";

/** The `.gitignore` files of a tree listing (paths), shallower first, then by path. */
export const gitignores = (paths) => paths.filter((p) => p === ".gitignore" || p.endsWith("/.gitignore"))
  .sort((a, b) => a.split("/").length - b.split("/").length || (a < b ? -1 : a > b ? 1 : 0));

/** The patterns of one `.gitignore` text: blank lines and comments dropped, trailing spaces trimmed. */
export const patternsOf = (text) => String(text).split("\n").map((l) => l.replace(/\r$/, "").replace(/(?<!\\)\s+$/, "")).filter((l) => l && !l.startsWith("#"));

/** One nested pattern rewritten under folder `dir` (no trailing slash). */
export function prefixed(dir, pattern) {
  const negated = pattern.startsWith("!"), raw = negated ? pattern.slice(1) : pattern;
  const trailing = raw.endsWith("/"), body = trailing ? raw.slice(0, -1) : raw;
  const anchored = body.includes("/");
  const out = anchored ? `${dir}/${body.replace(/^\/+/, "")}` : `${dir}/**/${body}`;
  return `${negated ? "!" : ""}${out}${trailing ? "/" : ""}`;
}

/** The last generated rule (F-031 Q1): every `.git` path un-matched, so a two-sided `.git` change stops the range. */
export const LWW_GIT_RULE = "!/.git";

/**
 * The `/.lww` text for a tree: `files` maps each `.gitignore` path to its text.
 * Returns the text and the rule count per source file.
 */
export function generateLww(files) {
  const lines = ["# generated by the #352 replay from every .gitignore (owner, 2026-10-18); do not edit"], sources = {};
  for (const path of gitignores([...files.keys()])) {
    const dir = path === ".gitignore" ? "" : path.slice(0, -"/.gitignore".length);
    const rules = patternsOf(files.get(path)).map((p) => (dir ? prefixed(dir, p) : p));
    sources[path] = rules.length;
    lines.push(`# ${path}`, ...rules);
  }
  // F-031 Q1 (owner 2026-10-19): last, so /.lww never decides a .git path, whatever a .gitignore lists (git never ignores .git)
  lines.push("# F-031 Q1: never a .git path", LWW_GIT_RULE);
  return { text: `${lines.join("\n")}\n`, sources };
}

// lww.rs parse and match, ported
function parse(line) {
  const negated = line.startsWith("!");
  let body = negated ? line.slice(1) : line;
  if (body.endsWith("/")) body = body.slice(0, -1);
  const anchored = body.includes("/");
  if (body.startsWith("/")) body = body.slice(1);
  const tokens = [];
  const cs = [...body];
  for (let i = 0; i < cs.length; i++) {
    const c = cs[i];
    if (c === "*" && cs[i + 1] === "*") {
      i++;
      const last = tokens.at(-1);
      if ((last === undefined || last === "/" || last?.t === "dirs") && cs[i + 1] === "/") { i++; tokens.push({ t: "dirs" }); } else tokens.push({ t: "any" });
    } else if (c === "*") tokens.push({ t: "name" });
    else if (c === "?") tokens.push({ t: "one" });
    else tokens.push(c);
  }
  return { pattern: line, negated, anchored, tokens };
}

function matchesFrom(rule, path, start, whole) {
  const n = path.length;
  let current = new Array(n + 1).fill(false);
  current[start] = true;
  for (const tok of rule.tokens) {
    const next = new Array(n + 1).fill(false);
    if (typeof tok === "string") { for (let p = 0; p < n; p++) next[p + 1] = current[p] && path[p] === tok; }
    else if (tok.t === "one") { for (let p = 0; p < n; p++) next[p + 1] = current[p] && path[p] !== "/"; }
    else if (tok.t === "name") {
      for (let p = 0; p <= n; p++) if (current[p]) { next[p] = true; let q = p; while (q < n && path[q] !== "/") { q++; next[q] = true; } }
    } else if (tok.t === "any") {
      const first = current.indexOf(true);
      if (first >= 0) for (let p = first; p <= n; p++) next[p] = true;
    } else {
      const first = current.indexOf(true);
      if (first >= 0) { for (let p = 0; p <= n; p++) next[p] = current[p]; for (let p = first; p < n; p++) if (path[p] === "/") next[p + 1] = true; }
    }
    current = next;
  }
  for (let p = 0; p <= n; p++) if (current[p] && (p === n || (!whole && path[p] === "/"))) return true;
  return false;
}

/** Parses rule-file text (comments and blank lines dropped; no %include). */
export const parseRules = (text) => String(text).split("\n").map((l) => l.trim()).filter((l) => l && !l.startsWith("#") && !l.startsWith("%include")).map(parse);

/** lww.rs `Rules::matching`: the deciding rule for a path, or null. */
export function lwwMatch(rules, path) {
  const cs = [...String(path).replace(/^\/+/, "")];
  let hit = null;
  for (const rule of rules) {
    const starts = [0, ...(rule.anchored ? [] : cs.flatMap((c, i) => (c === "/" ? [i + 1] : [])))];
    if (starts.some((s) => matchesFrom(rule, cs, s, false))) hit = rule.negated ? null : rule;
  }
  return hit;
}

/** `.git` paths the Q1 assertion checks: every file kind the seed, a lane and the lead write. */
export const GIT_PROBES = [".git", ".git/HEAD", ".git/index", ".git/config", ".git/logs/HEAD", ".git/refs/heads/main", ".git/refs/heads/lanes/r015-1-a",
  ".git/objects/pack/pack-0000000000000000000000000000000000000000.pack", ".git/objects/ab/cdef0000000000000000000000000000000000", ".git/worktrees/r015-1-a/index", ".git/worktrees/r015-1-a/HEAD"];

/**
 * The proof against git (owner S4): at range k's checkpoint, natively in the
 * image, with the install and the build's ignored output present, every path
 * git's check-ignore rules call ignored must match /.lww, and every
 * non-ignored path must not. Both lists come from `git ls-files --others`
 * in a fresh repository (no index, so every file is "other").
 */
export function checkAgainstGit({ repo, checkpoint, image, volume, build = [] }) {
  const { execFileSync, spawnSync } = childProcess;
  const tree = execFileSync("git", ["--git-dir", repo, "ls-tree", "-r", "--name-only", checkpoint], { encoding: "utf8", maxBuffer: 1 << 28 }).split("\n").filter(Boolean);
  const texts = new Map(gitignores(tree).map((p) => [p, execFileSync("git", ["--git-dir", repo, "show", `${checkpoint}:${p}`], { encoding: "utf8" })]));
  const { text } = generateLww(texts), rules = parseRules(text);
  const script = [`mkdir /w && tar -x -C /w && cd /w`, `(${closure.installCommand()}) > /dev/null 2>&1`, ...(build.length ? [`(${closure.buildCommand(build)}) > /dev/null 2>&1`] : []),
    `git init -q . && echo @@IGNORED && git ls-files --others --ignored --exclude-standard && echo @@KEPT && git ls-files --others --exclude-standard`].join("; ");
  const archive = execFileSync("git", ["--git-dir", repo, "archive", checkpoint], { maxBuffer: 1 << 30 });
  const r = spawnSync("docker", ["run", "--rm", "-i", "--name", `${process.env.LFS_RESOURCE_PREFIX ?? "layerfs-issue352"}-lwwcheck`, "--network", "none", "-v", `${volume}:${closure.STORE_MOUNT}:ro`, "--entrypoint", "sh", image, "-c", script], { input: archive, encoding: "utf8", maxBuffer: 1 << 29 });
  if (r.status !== 0) throw new Error(`lww check container exited ${r.status}: ${String(r.stderr).slice(-300)}`);
  const out = r.stdout.split("\n"), at = out.indexOf("@@IGNORED"), kept = out.indexOf("@@KEPT");
  const ignored = out.slice(at + 1, kept).filter(Boolean), notIgnored = out.slice(kept + 1).filter(Boolean);
  const missed = ignored.filter((p) => !lwwMatch(rules, p)), wrong = notIgnored.filter((p) => lwwMatch(rules, p));
  // F-031 Q1: no .git path may match, including names a .gitignore could list (index, logs/, *.pack)
  const gitMatched = GIT_PROBES.filter((p) => lwwMatch(rules, p));
  if (gitMatched.length) throw new Error(`/.lww matches .git paths (F-031 Q1): ${gitMatched.join(", ")}`);
  return { gitProbes: GIT_PROBES.length, gitMatched: 0, lines: text.split("\n").filter((l) => l && !l.startsWith("#")).length, bytes: Buffer.byteLength(text), ignored: ignored.length, notIgnored: notIgnored.length, missed: missed.length, wrong: wrong.length, missedSample: missed.slice(0, 10), wrongSample: wrong.slice(0, 10) };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const args = process.argv.slice(2), opt = (n) => { const i = args.indexOf(n); return i < 0 ? null : args[i + 1]; };
  if (args[0] !== "check" || !opt("--repo") || !opt("--checkpoint") || !opt("--image") || !opt("--volume")) {
    console.error("usage: lww.mjs check --repo R --checkpoint C --image I --volume V [--build p1,p2]"); process.exit(2);
  }
  console.log(JSON.stringify(checkAgainstGit({ repo: opt("--repo"), checkpoint: opt("--checkpoint"), image: opt("--image"), volume: opt("--volume"), build: opt("--build") ? opt("--build").split(",") : [] }), null, 1));
}
