// Headless walk-through of the three CLIs. Usage: node sdk_sim/test_terminal.js
"use strict";
const { SimBackend } = require("./simulation_engine/backend/sim.js");
const { Engine } = require("./simulation_engine/terminal.js");
const SCN = require("./scenarios.js");
(async () => {
const sim = new SimBackend();
await sim.reset(SCN[0].steps[0].args.files);
const e = new Engine(sim, "website");
const fsState = {};
let failed = 0;
const show = (who, line, rec) => { console.log(`${who}> ${line}`); for (const l of rec.lines) console.log(`   ${l.c ? "[" + l.c + "] " : ""}${l.t}`); };
const expect = (cond, msg) => { if (!cond) { failed++; console.log("   FAIL: " + msg); } };
const H = async (line) => { const r = await e.history(line); show("history", line, r); return r; };
const F = async (b, line) => { const r = await e.fs(b, line, fsState[b] ||= {}); show("fs:" + b, line, r); return r; };
let ws;
const X = async (line) => { const r = await e.sandbox(ws, line); show("sb", line, r); return r; };

expect((await H("fork feature-home")).forked === "feature-home", "fork opens tab");
await F("feature-home", 'edit /app/page.tsx "Hello world" "Welcome to LayerFS"');
await F("feature-home", "mkdir /app/about");
await F("feature-home", "cp /app/page.tsx /app/about/page.tsx");
await F("feature-home", "write /app/about/page.tsx <<EOF");
await F("feature-home", "export default function Page() {");
await F("feature-home", "  return <main><h1>We're building with LayerFS</h1></main>;");
await F("feature-home", "}");
let r = await F("feature-home", "EOF");
expect(r.calls[0].outcome.code === "Committed", "heredoc write commits");
await F("feature-home", "apply");
await F("feature-home", "write /README.md \"# Website\\n\\nBuilt with LayerFS\"");
await F("feature-home", "mv /app/about /app/info");
await F("feature-home", "mv /app/info /app/about");
r = await F("feature-home", "done");
expect(r.calls.length === 1 && r.calls[0].call === "fs.apply", "batch is one fs.apply");
await F("main", "write /x \"y\"");
const o = await e.openSandbox("feature-home", null); ws = o.binding; show("open", "sandbox on feature-home", o.rec);
r = await F("feature-home", 'edit /README.md "Website" "Site"');
expect(r.calls[0].outcome.code === "Committed" && r.lines.some((l) => /now stale/.test(l.t)), "fs write allowed while mounted, mount goes stale");
await X("npm run build");
await X("npm ci");
r = await X("npm run build");
expect(r.calls[0].outcome.code === "exit:1", "lint failure");
await X(`sed -i "s/We're/We\\&apos;re/" app/about/page.tsx`);
await X("cat app/about/page.tsx | grep h1");
r = await X("npm run build");
expect(r.calls[0].outcome.code === "exit:0", "build passes");
await X("npm run start");
r = await X("npm run start &");
expect(r.calls[0].outcome.code === "running", "server starts");
await X("curl -s http://localhost:3000/about");
await X("echo hello > notes.txt && cat notes.txt");
r = await X("unmount");
expect(r.calls[0].outcome.code === "Busy", "busy while server runs");
await sim.run("process.cancel", { sandbox: ws.sandbox, process: "proc_01" });
r = await X("commit");
expect(r.calls[0].outcome.code === "Committed" && r.calls[0].outcome.result.merged, "stale workspace commit merges cleanly");
r = await X("unmount");
expect(r.closed, "unmount closes terminal");
await H("log feature-home");
await H("diff main feature-home");
await H("fork header");
await H("publish feature-home");
await F("header", 'write /app/header.tsx "export const Header = () => <header/>;"');
r = await H("publish header");
expect(r.calls[0].outcome.code === "Added" && r.lines.some((l) => /main had moved to L1/.test(l.t)), "publish overwrites and warns");
await H("log main");
await H("branches");
r = await F("feature-home", "blame /app/about/page.tsx");
expect(r.files && r.files.mode === "blame" && r.lines.some((l) => /^C\d+ /.test(l.t)), "blame credits each line to a Commit");
expect(r.calls.some((c) => c.call === "fs.read"), "blame reads saved versions");
r = await F("main", "blame /app/page.tsx@L1");
expect(r.lines.some((l) => /^L0 /.test(l.t)) && r.lines.some((l) => /^C\d+ /.test(l.t)), "main blame credits L0 and the published Commits");
r = await F("feature-home", "open /README.md@C1");
expect(r.open && r.open.subject === "C1" && r.open.path === "/README.md", "open hands the Files pane a ref and path");

// .lww: a path both sides wrote goes to the newer write instead of conflicting.
await H("fork lww");
await F("lww", 'write /.lww "%include .gitignore"');
ws = (await e.openSandbox("lww", null)).binding;
await X("mkdir -p .next && echo workspace > .next/BUILD_ID");
await F("lww", "mkdir /.next");
await F("lww", 'write /.next/BUILD_ID "fs"');
r = await X("commit");
const lw = r.calls[0].outcome.result;
expect(r.calls[0].outcome.code === "Committed" && lw.merged.lww.length === 1 && sim.s.roots[lw.root]["/.next/BUILD_ID"].content === "fs", ".lww keeps the newer write");
expect(r.lines.some((l) => /last-writer-wins: \.next\/BUILD_ID/.test(l.t)), ".lww decision is reported");

// Conflict: rejected, markers written, Dirty unmount, fix, commit.
await F("lww", 'edit /README.md "# Website" "# Site from fs"');
await X('sed -i "s/# Website/# Site from the Workspace/" README.md');
r = await X("commit");
expect(r.calls[0].outcome.code === "Conflict" && r.lines.some((l) => /C README\.md/.test(l.t)), "conflict is rejected with the list");
r = await X("cat README.md");
expect(r.lines.some((l) => /^<<<<<<< workspace/.test(l.t)), "markers are written into the Workspace");
r = await X("unmount");
expect(r.calls[0].outcome.code === "Dirty" && !r.closed, "unmount refuses uncommitted work");
r = await X("commit");
expect(r.calls[0].outcome.code === "Conflict" && r.calls[0].outcome.refusal.markers, "commit refused while markers remain");
await X("sed -i '/Site from fs\\|^<<<<<<<\\|^=======\\|^>>>>>>>/d' README.md");
r = await X("commit");
expect(r.calls[0].outcome.code === "Committed", "commit after the fix");
await X("touch scratch.txt");
r = await X("unmount --discard");
expect(r.closed && r.calls[0].outcome.result.discardedUncommitted.includes("/scratch.txt"), "unmount --discard drops changes");

// a + b = c: inputs unchanged; a conflict creates c with markers and rejects.
const before = sim.s.branches.lww.head;
r = await H("merge lww main as lww-main");
expect(r.forked === "lww-main" && sim.s.branches.lww.head === before && sim.s.branches["lww-main"].head === before, "merge with an ancestor is metadata only and leaves its inputs");
r = await H("merge lww nope as x");
expect(r.calls[0].outcome.code === "NoSuchBranch" && !sim.s.branches.x, "merge with a missing source makes nothing");
await F("lww", 'edit /app/page.tsx "Hello world" "Hello lww"');
await H("fork other");
await F("other", 'edit /app/page.tsx "Hello world" "Hello other"');
r = await H("merge lww other as both");
expect(r.calls[0].outcome.code === "Conflict" && !sim.s.branches.both && !r.forked, "merge conflict creates nothing");
expect(r.lines.some((l) => /Hello lww/.test(l.t)) && r.lines.some((l) => /Hello other/.test(l.t)), "merge conflict shows both sides' lines");
await F("other", 'edit /app/page.tsx "Hello other" "Hello lww"');
r = await H("merge lww other as both");
expect(r.calls[0].outcome.code === "Merged" && sim.s.branches.both, "merge again after the sides agree");
console.log(failed ? `\n${failed} FAILED` : "\nall expectations met");
process.exit(failed ? 1 : 0);
})();
